/** تولید مقالهٔ قطعی برای یک تاپیک — بدون LLM */
export function generateTemplateArticle(
  topicRaw: TopicBrief,
  related: { slug: string; title: string }[] = []
): { html: string; validation: ReturnType<typeof validateArticle> } {
  // نرمال‌سازی ارقام تاپیک (۱۶۹ → ۱۶۹ فارسی) — عنوان/کلیدواژه/بریف
  const topic: TopicBrief = {
    ...topicRaw,
    title: faDigits(topicRaw.title),
    focusKeyword: faDigits(topicRaw.focusKeyword),
    brief: faDigits(topicRaw.brief),
  };
  const rnd = mulberry32(seedOf(topic.slug));
  const clusterKey = CLUSTER_SECTIONS[topic.cluster] ? topic.cluster : "accounting";
  const clusterBuilt = CLUSTER_SECTIONS[clusterKey].map((fn) => fn(topic, rnd));
  const generic = genericSections(topic, rnd);

  // بخش «زاویهٔ اختصاصی» — از بریف خود تاپیک
  const angleSection = `
<h2>زاویهٔ این مقاله: ${topic.title}</h2>
<p>${topic.brief}</p>
<p>این دقیقاً همانجایی است که ابزارِ درست، فرق را نشان می‌دهد: به‌جای اینکه این موارد را در چند اکسل و ذهن آدم‌ها نگه دارید، به‌صورت روالِ ثبت‌شده در سیستم می‌آیند — با هشدارهای خودکار برای مواردِ «فراموش‌شدنی» (سررسید، سقف اعتبار، نقطهٔ سفارش) و گزارش‌هایی که خودشان ساخته می‌شوند. اگر می‌خواهید همین حالا روی دادهٔ خودتان امتحانش کنید، ۷ روز رایگان و بدون کارت بانکی در اختیارتان است.</p>`;

  const parts: string[] = [
    introSection(topic, rnd),
    angleSection,
    ...clusterBuilt,
    ...generic,
    ctaBlock(topic),
    faqSection(topic, rnd),
    relatedBlock(
      topic,
      related.length > 0
        ? related
        : [
            { slug: "cloud-accounting-software-what-is-1404", title: "حسابداری ابری چیست؟" },
            { slug: "store-accounting-from-zero", title: "حسابداری فروشگاه از صفر" },
            { slug: "choose-accounting-software-15-criteria", title: "۱۵ معیار انتخاب نرم‌افزار" },
          ]
    ),
  ];

  let html = parts.join("\n");
  html = stripCJK(html);

  // تزریق تصویر بعد از اولین جدول (اگر LLM نبود هم تصویر باشد)
  const imgTag = `<img src="${topic.coverImage}" alt="${topic.title}" loading="lazy" width="1152" height="864" />`;
  const tIdx = html.indexOf("</table>");
  if (tIdx > -1) html = html.slice(0, tIdx + 8) + "\n" + imgTag + html.slice(tIdx + 8);

  let validation = validateArticle(html);
  // تضمین طول: بخش‌های تکمیلیِ «متمایز» (نه تکراری) تا عبور از ۳۰۵۰ کلمه
  let guard = 0;
  while (validation.words < 3050 && guard < EXTRA_SECTIONS.length) {
    html += "\n" + EXTRA_SECTIONS[guard](topic, rnd) + "\n";
    validation = validateArticle(html);
    guard++;
  }
  return { html, validation };
}

