// ───────────── PRNG قطعی (seed از slug) ─────────────
function seedOf(slug: string): number {
  let h = 0;
  for (let i = 0; i < slug.length; i++) h = (h * 31 + slug.charCodeAt(i)) >>> 0;
  return h >>> 0;
}
function mulberry32(a: number): () => number {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function shuffle<T>(items: T[], rnd: () => number): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
function pick<T>(arr: T[], rnd: () => number): T {
  return arr[Math.floor(rnd() * arr.length)];
}
/** عدد فارسی با جداکنندهٔ هزارگان */
function fa(n: number): string {
  return n.toLocaleString("fa-IR");
}
/** «۲۰»٪ و غیره — درصد فارسی */
function faPct(n: number): string {
  return `${fa(n)}٪`;
}
/** تبدیل ارقام لاتین به فارسی — بانک موضوع بعضی جاها ۱۶۹ لاتین دارد */
function faDigits(text: string): string {
  const map = "۰۱۲۳۴۵۶۷۸۹";
  return text.replace(/[0-9]/g, (d) => map[Number(d)]);
}

/** مقدار پول تومانی — بر اساس seed کمی متغیر تا مثال‌ها تکراری نشوند */
function money(base: number, rnd: () => number, variance = 0.15): number {
  const factor = 1 + (rnd() - 0.5) * 2 * variance;
  return Math.round((base * factor) / 100_000) * 100_000; // گرد به ۱۰۰ هزار تومان
}

