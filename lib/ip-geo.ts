export interface IpGeoResult {
  country: string; // «ایران» یا نام کشور به فارسی
  countryCode: string; // "IR" یا کد کشور
  city: string | null; // نام شهر به فارسی — null = نامشخص
  province: string | null; // استان (فقط برای مدخل‌های قطعی)
  isp: string | null; // نام اپراتور/ISP فارسی — قابل‌اتکا حتی بدون شهر
  isVpn: boolean; // مشکوک به VPN/دیتاسنتر
  isLocal: boolean; // localhost یا شبکهٔ داخلی
  source: "local" | "cache" | "online" | "unknown"; // منبع تشخیص
  lat: number | null;
  lng: number | null;
}

