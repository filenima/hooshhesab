/* ---------------- خلاصهٔ مکان برای UI ---------------- */

export function formatLocation(geo: IpGeoResult): string {
  if (geo.isLocal) return "شبکهٔ داخلی";
  if (geo.country === "ایران") {
    if (geo.city) return geo.province ? `${geo.city}، ${geo.province}` : `${geo.city}، ایران`;
    if (geo.isp) return `ایران (${geo.isp}) — شهر نامشخص`;
    return "ایران — شهر نامشخص";
  }
  if (geo.isVpn) return "خارج (مشکوک به VPN)";
  return geo.country;
}

/* ================================================================
 *  لایهٔ ۲ و ۳ — resolveIpGeo: کش دیتابیس + غنی‌سازی آنلاین
 * ============================================================== */

const ONLINE_TIMEOUT_MS = 3500;
const CACHE_STALE_DAYS = 180; // بعد از ۶ ماه یک بار تازه‌سازی
const memoryGeoCache = new Map<string, IpGeoResult>();
const MEMORY_CACHE_MAX = 3000;

/** ترجمهٔ نام کشورهای پرتکرار به فارسی */
const COUNTRY_FA: Record<string, string> = {
  US: "آمریکا", DE: "آلمان", NL: "هلند", FR: "فرانسه", GB: "انگلستان",
  TR: "ترکیه", AE: "امارات", CA: "کانادа", SE: "سوئد", FI: "فنلاند",
  CH: "سوئیس", AT: "اتریش", RU: "روسیه", CN: "چین", IN: "هند",
  JP: "ژاپن", KR: "کره جنوبی", SG: "سنگاپور", AU: "استرالیا",
  IQ: "عراق", AZ: "آذربایجان", AF: "افغانستان", PK: "پاکستان",
  SA: "عربستان", KW: "کویت", QA: "قطر", OM: "عمان", BH: "بحرین",
};

function normalizeCityName(city: string): string | null {
  if (!city || city.length < 2) return null;
  return city.trim() || null;
}

/** غنی‌سازی آنلاین از ipwho.is — بدون کلید، HTTPS، ۳.۵ ثانیه سقف */
async function fetchGeoOnline(ip: string): Promise<{
  city: string | null; region: string | null; country: string | null;
  countryCode: string | null; isp: string | null; lat: number | null; lng: number | null;
  success: boolean;
} | null> {
  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), ONLINE_TIMEOUT_MS);
    const res = await fetch(`https://ipwho.is/${encodeURIComponent(ip)}`, {
      signal: controller.signal,
      headers: { "User-Agent": "HooshHesab-Geo/1.0" },
      cache: "no-store",
    });
    clearTimeout(timer);
    if (!res.ok) return null;
    const json = (await res.json()) as Record<string, unknown>;
    if (json.success !== true) return { success: false, city: null, region: null, country: null, countryCode: null, isp: null, lat: null, lng: null };
    const connection = (json.connection || {}) as Record<string, unknown>;
    const lat = typeof json.latitude === "number" ? json.latitude : null;
    const lng = typeof json.longitude === "number" ? json.longitude : null;
    return {
      success: true,
      city: normalizeCityName(String(json.city || "")),
      region: json.region ? String(json.region) : null,
      country: json.country ? String(json.country) : null,
      countryCode: json.country_code ? String(json.country_code) : null,
      isp: connection.isp ? String(connection.isp) : (connection.org ? String(connection.org) : null),
      lat, lng,
    };
  } catch {
    return null; // آفلاین یا timeout — بی‌صدا رد شو
  }
}

function memoryCacheSet(ip: string, geo: IpGeoResult) {
  if (memoryGeoCache.size >= MEMORY_CACHE_MAX) memoryGeoCache.clear();
  memoryGeoCache.set(ip, geo);
}

/**
 * resolveIpGeo — مسیر کامل سه‌لایه (کش حافظه → کش دیتابیس → آنلاین → استاتیک).
 * حالت پیش‌فرض online=true یعنی اگر کش نبود از اینترنت بپرس؛
 * برای مسیرهای حساس به تأخیر (صف ورود) online=false بگذارید و
 * enrichIpGeo جداگانه در پس‌زمینه صدا زده می‌شود.
 */
export async function resolveIpGeo(ip: string, opts?: { online?: boolean }): Promise<IpGeoResult> {
  if (isLocalIp(ip)) return lookupIp(ip);

  // ۱) کش حافظهٔ پروسه
  const mem = memoryGeoCache.get(ip);
  if (mem) return mem;

  const local = lookupIp(ip);

  // ۲) کش دیتابیس
  try {
    const row = await db.ipGeoCache.findUnique({ where: { ip } });
    if (row) {
      const ageDays = (Date.now() - new Date(row.fetchedAt).getTime()) / 86_400_000;
      const usable =
        row.source === "online" && ageDays < CACHE_STALE_DAYS
          ? true
          : row.source === "failed" && ageDays < 7
            ? false // شکست اخیر → دوباره امتحان نکن (تا ۷ روز)
            : ageDays < CACHE_STALE_DAYS;
      if (usable) {
        const geo: IpGeoResult = {
          country: row.countryCode === "IR" ? "ایران" : (COUNTRY_FA[row.countryCode || ""] || row.country || "خارج"),
          countryCode: row.countryCode || "??",
          city: row.city,
          province: row.region,
          isp: row.isp,
          isVpn: false,
          isLocal: false,
          source: "cache",
          lat: row.lat,
          lng: row.lng,
        };
        memoryCacheSet(ip, geo);
        return geo;
      }
    }
  } catch {
    /* DB در دسترس نیست → ادامه با استاتیک */
  }

  // ۳) غنی‌سازی آنلاین (اختیاری)
  if (opts?.online !== false) {
    const online = await fetchGeoOnline(ip);
    if (online && online.success) {
      const isIr = online.countryCode === "IR";
      const geo: IpGeoResult = {
        country: isIr ? "ایران" : (COUNTRY_FA[online.countryCode || ""] || online.country || "خارج"),
        countryCode: online.countryCode || "??",
        city: online.city,
        province: online.region,
        isp: online.isp,
        isVpn: !isIr && FOREIGN_DATACENTER_PREFIXES.some((p) => ip.startsWith(p)),
        isLocal: false,
        source: "online",
        lat: online.lat,
        lng: online.lng,
      };
      memoryCacheSet(ip, geo);
      // ذخیرهٔ دائمی در کش دیتابیس (یک IP یک بار پرسیده می‌شود)
      db.ipGeoCache.upsert({
        where: { ip },
        create: {
          ip, city: online.city, region: online.region,
          country: online.country, countryCode: online.countryCode,
          isp: online.isp, lat: online.lat, lng: online.lng,
          source: "online", fetchedAt: new Date(),
        },
        update: {
          city: online.city, region: online.region,
          country: online.country, countryCode: online.countryCode,
          isp: online.isp, lat: online.lat, lng: online.lng,
          source: "online", fetchedAt: new Date(),
        },
      }).catch(() => { /* کش نوشته نشد → مهم نیست */ });
      return geo;
    }
    // آنلاین شکست خورد — عقب‌افتادگی را ثبت کن تا ۷ روز دوباره نپرسیم
    if (online && !online.success) {
      db.ipGeoCache.upsert({
        where: { ip },
        create: { ip, source: "failed", fetchedAt: new Date() },
        update: { source: "failed", fetchedAt: new Date() },
      }).catch(() => { /* بی‌اهمیت */ });
    }
  }

  // ۴) خروجی استاتیک صادقانه
  memoryCacheSet(ip, local);
  return local;
}

/**
 * enrichIpGeo — غنی‌سازی در پس‌زمینه (fire-and-forget).
 * بعد از ورود موفق صدا زده می‌شود؛ هرگز نتیجه را منتظر نکنید.
 */
export function enrichIpGeo(ip: string): void {
  if (isLocalIp(ip)) return;
  void resolveIpGeo(ip, { online: true }).catch(() => { /* بی‌صدا */ });
}

/** پاک‌سازی کش حافظه (برای تست‌ها) */
export function clearIpGeoMemoryCache(): void {
  memoryGeoCache.clear();
}
