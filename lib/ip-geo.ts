/* ---------------- تبدیل و تطبیق ---------------- */

function ipToInt(ip: string): number | null {
  const parts = ip.split(".");
  if (parts.length !== 4) return null;
  const nums = parts.map((p) => parseInt(p, 10));
  if (nums.some((n) => isNaN(n) || n < 0 || n > 255)) return null;
  return ((nums[0] << 24) + (nums[1] << 16) + (nums[2] << 8) + nums[3]) >>> 0;
}

function isLocalIp(ip: string): boolean {
  if (!ip || ip === "unknown" || ip === "::1" || ip === "localhost") return true;
  return VPN_SUSPICIOUS_PREFIXES.some((p) => ip.startsWith(p));
}

// کش نقطه‌ای برای ipToInt (پرهیز از بازمحاسبه در جستجوی خطی)
const intCache = new Map<string, number | null>();
function ipToIntCached(ip: string): number | null {
  if (intCache.has(ip)) return intCache.get(ip) ?? null;
  const v = ipToInt(ip);
  if (intCache.size > 5000) intCache.clear();
  intCache.set(ip, v);
  return v;
}

/** تطبیق طولانی‌ترین پیشوند — بین همهٔ مدخل‌های منطبق، باریک‌ترین برنده است */
function matchRanges(ipInt: number): StaticRange[] {
  const matches: StaticRange[] = [];
  for (const r of CITY_SPECIFIC_RANGES) {
    const s = ipToIntCached(r.start);
    const e = ipToIntCached(r.end);
    if (s !== null && e !== null && ipInt >= s && ipInt <= e) matches.push(r);
  }
  for (const r of IRAN_NATIONAL_RANGES) {
    const s = ipToIntCached(r.start);
    const e = ipToIntCached(r.end);
    if (s !== null && e !== null && ipInt >= s && ipInt <= e) matches.push(r);
  }
  if (matches.length > 1) {
    matches.sort((a, b) => {
      const sa = ipToIntCached(a.end)! - ipToIntCached(a.start)!;
      const sb = ipToIntCached(b.end)! - ipToIntCached(b.start)!;
      return sa - sb; // باریک‌ترین (مخصوص‌ترین) اول
    });
  }
  return matches;
}

