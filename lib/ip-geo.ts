// چرا بازنویسی شد؟ جدول قبلی دو باگ بنیادین داشت:
//   ۱) محدوده‌های هم‌پوشان (مثلاً کل 5.112.0.0–5.127.255.255 = «تهران» که
//      روی محدودهٔ «کرج» و «ساری» و … می‌افتاد) و «اولین تطبیق برنده می‌شد»؛
//      نتیجه: تقریباً همهٔ IPهای ایران «تهران» نمایش داده می‌شدند — غلط.
//   ۲) غلبهٔ دقت کاذب: به بلوک‌های «ملیِ» ISPها (مخابرات، شاتل و…) شهر نسبت
//      می‌داد در حالی که این بلوک‌ها در همهٔ استان‌ها تخصیص پویا دارند.
//
// معماری جدید — سه لایهٔ صادقانه:
//   لایهٔ ۱ (محلی، آفلاین): جدول استاتیک «بدون هم‌پوشانی» با تطبیق
//      طولانی‌ترین پیشوند (most-specific wins) — فقط مدخل‌های قطعی.
//      کشور ایران + نام ISP (قابل‌اتکا) + شهر فقط برای بلوک‌های مشخصِ شهر.
//   لایهٔ ۲ (کش دیتابیس): جدول IpGeoCache — نتیجهٔ غنی‌سازی آنلاین برای
//      هر IP یک بار ذخیره می‌شود و همیشه از کش خوانده می‌شود.
//   لایهٔ ۳ (آنلاین): ipwho.is (HTTPS بدون کلید، ۳ ثانیه سقف) — در پس‌زمینه
//      صدا زده می‌شود؛ اگر اینترنت نباشد بی‌صدا رد می‌شود.
//
// اصل صداقت: هرگز شهرِ نامعلوم را «تهران» نشان نمی‌دهیم؛
// «ایران — شهر نامشخص» + نام ISP درست‌تر و حرفه‌ای‌تر است.
// ============================================================================

