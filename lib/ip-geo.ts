export function lookupIp(ip: string): IpGeoResult {
  if (isLocalIp(ip)) {
    return {
      country: "ایران", countryCode: "IR", city: null, province: null,
      isp: null, isVpn: false, isLocal: true, source: "local", lat: null, lng: null,
    };
  }

  // IPv6 — ساده‌سازی: با غنی‌سازی آنلاین کامل می‌شود
  if (ip.includes(":")) {
    return {
      country: "نامشخص", countryCode: "??", city: null, province: null,
      isp: null, isVpn: false, isLocal: false, source: "unknown", lat: null, lng: null,
    };
  }

  const ipInt = ipToInt(ip);
  if (ipInt === null) {
    return {
      country: "نامشخص", countryCode: "??", city: null, province: null,
      isp: null, isVpn: false, isLocal: false, source: "unknown", lat: null, lng: null,
    };
  }

  const matches = matchRanges(ipInt);
  if (matches.length > 0) {
    const best = matches[0]; // مخصوص‌ترین تطبیق
    return {
      country: "ایران", countryCode: "IR",
      city: best.city ?? null, // null = شهر نامشخص — صادقانه
      province: best.province ?? null,
      isp: best.isp ?? null,
      isVpn: false, isLocal: false, source: "local", lat: null, lng: null,
    };
  }

  // IP خارجی — بررسی دیتاسنتر VPN
  const isVpn = FOREIGN_DATACENTER_PREFIXES.some((p) => ip.startsWith(p));
  return {
    country: "خارج", countryCode: "??", city: null, province: null,
    isp: null, isVpn, isLocal: false, source: "unknown", lat: null, lng: null,
  };
}

